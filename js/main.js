function applyLanguage(lang) {
  const t = translations[lang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const val = t[el.dataset.i18n];
    if (!val) return;
    if (/<[a-z]/i.test(val)) {
      // value contains HTML tags — use innerHTML
      el.innerHTML = val;
    } else {
      // plain text — preserve child elements (e.g. faq__icon span)
      const childEls = Array.from(el.childNodes).filter(n => n.nodeType === 1);
      if (childEls.length) {
        Array.from(el.childNodes).filter(n => n.nodeType === 3).forEach(n => n.remove());
        el.insertBefore(document.createTextNode(val), el.firstChild);
      } else {
        el.textContent = val;
      }
    }
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    if (t[el.dataset.i18nHtml]) el.innerHTML = t[el.dataset.i18nHtml];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    if (t[el.dataset.i18nPlaceholder]) el.placeholder = t[el.dataset.i18nPlaceholder];
  });
  document.querySelectorAll('.lang-switcher__btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  localStorage.setItem('vbc-lang', lang);
  if (window.updateChatbotLang) window.updateChatbotLang(lang);
}

const langSwitcher = document.getElementById('langSwitcher');
const langToggle = document.getElementById('langToggle');
const langBtns = document.querySelectorAll('.lang-switcher__btn');

if (langToggle) {
  langToggle.addEventListener('click', e => {
    e.stopPropagation();
    langSwitcher.classList.toggle('open');
  });
  document.addEventListener('click', () => langSwitcher.classList.remove('open'));
  langSwitcher.querySelector('.lang-switcher__dropdown').addEventListener('click', e => e.stopPropagation());
}

langBtns.forEach(btn => btn.addEventListener('click', () => {
  applyLanguage(btn.dataset.lang);
  langSwitcher.classList.remove('open');
}));

const savedLang = localStorage.getItem('vbc-lang');
if (savedLang && savedLang !== 'es') applyLanguage(savedLang);

/* ================================
   SUBSCRIBE MODAL
================================ */
(function() {
  const btn = document.getElementById('subscribeBtn');
  const modal = document.getElementById('subscribeModal');
  const backdrop = document.getElementById('subscribeBackdrop');
  const closeBtn = document.getElementById('subscribeClose');
  const form = document.getElementById('subscribeForm');
  if (!btn || !modal) return;

  btn.addEventListener('click', () => modal.classList.add('open'));
  backdrop.addEventListener('click', () => modal.classList.remove('open'));
  closeBtn.addEventListener('click', () => modal.classList.remove('open'));
  document.addEventListener('keydown', e => { if (e.key === 'Escape') modal.classList.remove('open'); });

  form.addEventListener('submit', e => {
    e.preventDefault();
    const email = form.querySelector('input[type="email"]').value;
    const consent = document.getElementById('subscribeConsent');
    if (!consent.checked) { consent.focus(); return; }
    const box = form.closest('.subscribe-modal__box');

    fetch('/subscribe.php', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ email })
    });

    box.innerHTML = `
      <div class="subscribe-modal__success">
        <div style="font-size:48px;margin-bottom:16px;">✓</div>
        <h4>¡Suscripción confirmada!</h4>
        <p>Te enviaremos resultados, horarios y novedades de cada torneo a <strong>${email}</strong>.</p>
      </div>`;
    setTimeout(() => modal.classList.remove('open'), 3000);
  });
})();

